
"""PDF report generation."""

from io import BytesIO
from xml.sax.saxutils import escape

import pandas as pd

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import (
    getSampleStyleSheet,
    ParagraphStyle,
)
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)


def _safe_text(value):
    if value is None:
        return ""

    return escape(str(value))


def _make_table(dataframe):
    if dataframe is None or dataframe.empty:
        return [
            Paragraph(
                "No tabular results available.",
                getSampleStyleSheet()["BodyText"],
            )
        ]

    frame = dataframe.copy().fillna("")
    frame = frame.astype(str)

    # Keep report tables manageable.
    frame = frame.iloc[:100, :8]

    data = [
        [_safe_text(column) for column in frame.columns]
    ]

    for row in frame.itertuples(index=False, name=None):
        data.append([
            _safe_text(value)[:250]
            for value in row
        ])

    table = Table(
        data,
        repeatRows=1,
        hAlign="LEFT",
    )

    table.setStyle(
        TableStyle([
            (
                "BACKGROUND",
                (0, 0),
                (-1, 0),
                colors.HexColor("#E7EFE7"),
            ),
            (
                "TEXTCOLOR",
                (0, 0),
                (-1, 0),
                colors.HexColor("#20372B"),
            ),
            (
                "GRID",
                (0, 0),
                (-1, -1),
                0.35,
                colors.HexColor("#CBD8CB"),
            ),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("FONTSIZE", (0, 0), (-1, -1), 7),
            ("LEADING", (0, 0), (-1, -1), 9),
            ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ])
    )

    return [table]


def generate_pdf_report(
    title,
    sections,
    author="GeneRescue AI",
):
    """
    Generate a PDF report.

    Example sections:
    [
        {
            "heading": "Input",
            "content": "Sequence accession: ABC123"
        },
        {
            "heading": "Results",
            "dataframe": results_df
        }
    ]
    """

    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=17 * mm,
        leftMargin=17 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title=str(title),
        author=str(author),
    )

    styles = getSampleStyleSheet()

    styles.add(
        ParagraphStyle(
            name="ResearchBody",
            parent=styles["BodyText"],
            leading=14,
            spaceAfter=6,
            alignment=TA_LEFT,
        )
    )

    story = [
        Paragraph(
            _safe_text(title),
            styles["Title"],
        ),
        Spacer(1, 5 * mm),
        Paragraph(
            f"Generated by {_safe_text(author)}",
            styles["Italic"],
        ),
        Spacer(1, 7 * mm),
    ]

    for section in sections:
        if not isinstance(section, dict):
            continue

        heading = section.get(
            "heading",
            "Research section",
        )

        story.append(
            Paragraph(
                _safe_text(heading),
                styles["Heading2"],
            )
        )

        if "dataframe" in section:
            dataframe = section["dataframe"]

            if isinstance(dataframe, pd.DataFrame):
                story.extend(_make_table(dataframe))
            else:
                story.append(
                    Paragraph(
                        "The supplied result is not a pandas DataFrame.",
                        styles["ResearchBody"],
                    )
                )

        elif "content" in section:
            content = section["content"]

            if isinstance(content, (dict, list, tuple)):
                content = str(content)

            story.append(
                Paragraph(
                    _safe_text(content),
                    styles["ResearchBody"],
                )
            )

        story.append(Spacer(1, 5 * mm))

    story.extend([
        Spacer(1, 5 * mm),
        Paragraph(
            "Research-support output. Computational predictions "
            "and database annotations require biological "
            "interpretation and independent experimental validation.",
            styles["Italic"],
        ),
    ])

    document.build(story)

    buffer.seek(0)

    return buffer


def create_research_report(
    title,
    sections,
    author="GeneRescue AI",
):
    """Compatibility wrapper for report generation."""
    return generate_pdf_report(
        title,
        sections,
        author,
    )
